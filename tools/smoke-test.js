'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const app = read('app-builtin.html');
const index = read('index.html');
const community = read('netlify/functions/community.js');
const release = read('netlify/functions/release.js');
const pkg = JSON.parse(read('package.json'));
const matchBuild = (s) => Number((s.match(/<meta\s+name="app-build"\s+content="(\d+)"/i) || [])[1]);

assert.strictEqual(pkg.version, '8.6.2', 'package release version');
assert.strictEqual(matchBuild(app), 818, 'built-in app build');
assert.strictEqual(matchBuild(index), 818, 'homepage build');
assert.match(index, /var BASE_BUILD = 818/);
assert.match(release, /const BASE_BUILD\s*=\s*818/);
assert.match(community, /b\.action === 'catalog_save'/);
assert.doesNotMatch(release, /b\.action === 'catalog_save'/, 'catalogue writes must not use release endpoint');

const catSave = app.match(/async function dvCatSave\(\)\{[\s\S]*?\n/);
assert(catSave && catSave[0].includes('dvCommunityApi'), 'catalogue save uses /api/community');
assert.match(app, /async function dvCatToggle\([\s\S]*?await dvCatSave\(\)/, 'retire/restore persists');
assert.match(app, /cur=CAT\.filter\(e=>e\.cur\)/, 'checklist filters active catalogue titles');
assert.match(app, /Add to checklist and shared catalogue/);
assert.match(app, /Active · included in checklist/);
assert.match(app, /Retired · hidden from current checklist/);

assert.match(app, /id="dvHotCode"/);
assert.match(app, /function dvRelPasteSubmit\(\)/);
assert.match(app, /dvApi\(\{action:'upload',label:/, 'paste mode submits complete HTML to release API');
assert.match(app, /maximum 1,536 KB/);
assert.match(app, /Run diagnostics/);
assert.match(app, /grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/, 'developer navigation uses mobile-safe grid');

assert.match(app, /function logout\(\)[\s\S]*?ls\.s\('state',null\)/, 'logout removes only the active profile state');
assert.match(app, /Logout keeps your data/);
assert.match(app, /Clear My Data will permanently erase[\s\S]*manual bonus-event names and points[\s\S]*Facilitator Program settings/);
assert.match(app, /Additional points included/);
assert.match(app, /Manual bonus events/);
assert.match(app, /Arcade Buddy/);
assert.match(app, /id="arcBotDock"/);
assert.match(app, /id="arcBotFab"/);
assert.match(app, /viewBox="0 0 56 64"/, 'launcher is a full-body tiny robot, not a circular logo');
assert.match(app, /id="arcBotMessages"/, 'assistant uses a minimal chat transcript');
assert.match(app, /Plan preferences/, 'planning preferences are collapsed by default');
assert.match(app, /No external AI model is connected/, 'assistant explains its provider status clearly');
assert.match(app, /function arcBotSend\(preset\)/);
assert.match(app, /function arcBotAddMessage\(role,text,evidence\)/, 'chat messages render as safe text bubbles with validated source links');
assert.match(app, /arc-bot-evidence/, 'completed research sources appear under the answer');
assert.doesNotMatch(app, /Checking your progress and verified programme feed/, 'no intermediate research status is shown');
assert.match(app, /id="arcBotHours"/);
assert.match(app, /arc-bot-dock.*left:16px/s);
assert.match(index, /id="arcBotDock"/);
assert.match(index, /id="arcBotMessages"/, 'homepage assistant uses the same chat interface');
assert.match(index, /viewBox="0 0 56 64"/, 'homepage uses the full-body robot');
assert.match(index, /function arcBotSend\(preset\)/);
assert.match(app, /dvSendAgentDigest/);
assert.doesNotMatch(app, /arcAgentGemini|GEMINI_API_KEY|Check AI setup|AIza[0-9A-Za-z_-]{20}/);
assert.doesNotMatch(read('netlify/functions/intelligence.js'), /GEMINI_API_KEY|generativelanguage\.googleapis\.com|callGemini/);
assert.match(read('netlify/functions/intelligence.js'), /externalAi: false/);
assert.match(read('netlify.toml'), /from = \"\/api\/intelligence\"/);
assert.match(read('netlify/functions/intelligence.js'), /human_review_required === false/);
assert.match(read('netlify/functions/intelligence.js'), /notification_approved === true/);
assert.match(app, /fresh=1[\s\S]*cache:'no-store'/);
assert.match(app, /Force refresh started/);
assert.ok(app.indexOf('facCard(c)}${manualEventsCard(c)}${gamesLink()}') > 0, 'dashboard sections ordered below progress');
console.log('Static smoke tests passed: catalogue routing, checklist persistence, logout/data-clear separation, dashboard layout, full-body Arcade Buddy robot, compact chat planner, rule-based planning without external AI, secure approved digest, refresh cache bypass, Hot Update paste UI, and synchronized build 818.');
